package dev.voicejournal.ui.designsystem.tokens

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * VoiceJournal Standard Icon Dimensions
 */
object IconSize {
    /** 14.dp — Micro icon (chip dismiss, inline tag indicator) */
    val IconXs: Dp = 14.dp

    /** 18.dp — Small icon (inline card indicators, checkmarks) */
    val IconSm: Dp = 18.dp

    /** 20.dp — Compact icon (audio play/pause, chevron actions) */
    val IconMd: Dp = 20.dp

    /** 24.dp — Standard Material Symbol icon size */
    val IconLg: Dp = 24.dp

    /** 32.dp — Large section icon / dialog header icon */
    val IconXl: Dp = 32.dp

    /** 64.dp — Hero lock screen & empty state hero icon */
    val IconHero: Dp = 64.dp
}
