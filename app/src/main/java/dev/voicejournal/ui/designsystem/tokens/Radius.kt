package dev.voicejournal.ui.designsystem.tokens

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * VoiceJournal Corner Radius Tokens
 */
object Radius {
    /** 4.dp — Extra small corner radius for micro tags/placeholders */
    val RadiusXs: Dp = 4.dp

    /** 8.dp — Small corner radius for inputs, thumbnails, badges */
    val RadiusSm: Dp = 8.dp

    /** 12.dp — Medium corner radius for standard cards & buttons */
    val RadiusMd: Dp = 12.dp

    /** 14.dp — Large corner radius for journal entry cards */
    val RadiusLg: Dp = 14.dp

    /** 20.dp / 24.dp — Pill radius for chips, action buttons, audio player bar */
    val RadiusPill: Dp = 24.dp

    /** 28.dp — Top corner radius for modal bottom sheets */
    val RadiusSheet: Dp = 28.dp
}
